def load_extra() -> list[dict[str, str]]:
    namespace: dict[str, object] = {"row": row}
    extra_path = Path(__file__).with_name("register_extra.py")
    exec(extra_path.read_text(encoding="utf-8"), namespace)
    return list(namespace["EXTRA"])  # type: ignore[arg-type]


def catalog_rows() -> list[dict[str, str]]:
    text = CATALOG.read_text(encoding="utf-8")
    rows: list[dict[str, str]] = []
    gate = "unscoped"
    for line in text.splitlines():
        heading = re.match(r"^## (.+)$", line)
        if heading:
            gate = heading.group(1)
            continue
        cells = [c.strip().strip("`") for c in line.strip("|").split("|")]
        if len(cells) != 3 or cells[0] in {"Phase or rule", "---"} or set(cells[0]) <= {"-", " "}:
            continue
        if not re.match(r"^[A-Z0-9_./-]+$", cells[0]):
            continue
        kind, confidence = cells[1], cells[2]
        rule_id = cells[0]
        obligation = "conditional" if rule_id.startswith("COMPOSE.") else "platform"
        risk = "U-SEVERITY-ALIGNMENT. Severity badges in the screenshots were not column-aligned, so this row does not assert REQUIRED versus OPTIONAL."
        if "CANARY" in rule_id:
            risk = "C-CANARY. " + risk
        if "ADVISORY" in rule_id:
            obligation = "advisory"
            risk = "Name contains ADVISORY, which p.11 says does not reject. " + risk
        gate_slug = re.sub(r"[^A-Za-z0-9]+", "-", gate.split()[0]).strip("-")
        rows.append(row(
            f"REQ-PL-{gate_slug}-{rule_id.replace('.', '-')}",
            obligation,
            "platform",
            "stage1",
            "pp. 12–13 screenshots; gate prose pp. 10–11",
            gate,
            f"Platform {kind} `{rule_id}` is visible under {gate}. Confidence: {confidence}. The author prevents the failing condition named by the rule and archives the live text if it fires.",
            "Stage 1 blocking reason is not this id, or the outcome is a documented retry rather than a task rewrite when the prose classifies it as platform-side.",
            "stage1.txt",
            risk,
            "00-source/PLATFORM-RULE-CATALOG.md",
        ))
    return rows


def render(rows: list[dict[str, str]]) -> None:
    ids = [item["id"] for item in rows]
    dupes = {i for i in ids if ids.count(i) > 1}
    if dupes:
        raise SystemExit(f"duplicate ids: {sorted(dupes)}")
    missing = []
    for item in rows:
        for field in FIELDS:
            if not str(item.get(field, "")).strip():
                missing.append((item["id"], field))
        path = ROOT / item["explained_in"]
        if not path.exists():
            missing.append((item["id"], f"missing file {item['explained_in']}"))
    if missing:
        raise SystemExit(f"incomplete rows: {missing[:12]}")
    counts: dict[str, int] = {}
    for item in rows:
        counts[item["obligation"]] = counts.get(item["obligation"], 0) + 1
    lines = [
        "# Requirements register",
        "",
        "Extracted from `Thanos _ Guidelines _ Onboarding SOP v3.0.pdf` (32 pages).",
        "Each row is one requirement. Platform rule IDs come from the Stage 1 screenshots and are catalogued, not guessed.",
        "Obligation classes are defined in `00-source/HOW-TO-READ.md`. Conflicts are decided only in `00-source/CONFLICT-REGISTER.md`.",
        "Superseded / newly introduced / unchanged / internally contradictory / practice classes: `00-source/REQUIREMENT-CLASSES.md` and `00-source/INVENTORY.md`.",
        "Retired previous-PDF numbers: `00-source/HISTORICAL-PREVIOUS-PDF.md` (not an active source).",
        "",
        f"Count: {len(rows)}.",
        "",
        "| Obligation | Rows |",
        "| --- | --- |",
    ]
    for key in ("mandatory", "conditional", "advisory", "platform", "unresolved", "example"):
        lines.append(f"| {key} | {counts.get(key, 0)} |")
    lines.extend(["", "Regenerate with `python3 tools/build_register.py`.", ""])
    for item in rows:
        lines.append(f"## {item['id']}")
        lines.append(f"- obligation: {item['obligation']}")
        lines.append(f"- scope: {item['scope']}")
        lines.append(f"- stages: {item['stages']}")
        lines.append(f"- source: {item['source']}")
        lines.append(f"- section: {item['section']}")
        lines.append(f"- explained_in: {item['explained_in']}")
        lines.append(f"- compliance_check: {item['compliance_check']}")
        lines.append(f"- evidence: {item['evidence']}")
        lines.append(f"- contradiction_or_rejection_risk: {item['contradiction_or_rejection_risk']}")
        lines.append(f"- requirement: {item['requirement']}")
        lines.append("")
    OUT_MD.write_text("\n".join(lines), encoding="utf-8")
    with OUT_CSV.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=FIELDS)
        writer.writeheader()
        writer.writerows(rows)
    print(f"wrote {OUT_MD.name} and {OUT_CSV.name}: {len(rows)} rows")


def main() -> None:
    rows = PROSE + load_extra() + catalog_rows()
    render(rows)


if __name__ == "__main__":
    main()

